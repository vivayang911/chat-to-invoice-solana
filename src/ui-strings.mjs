 if((m=/^(You · Seller|Jordan · Customer) · (M\d+)$/.exec(text)))return `${zh[m[1]]} · ${m[2]}`;
 if((m=/^Edit message (M\d+)$/.exec(text)))return `编辑消息 ${m[1]}`;
